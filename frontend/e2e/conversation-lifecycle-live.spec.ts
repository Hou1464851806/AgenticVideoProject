import { test, expect } from '@playwright/test';
import { createHash, randomUUID } from 'node:crypto';

// Opt-in harness: LocalMediaIntegrationTest supplies isolated PostgreSQL/MQ/storage and analysed media.
test.skip(process.env.E2E_LIFECYCLE_REAL !== '1', 'Run via LocalMediaIntegrationTest with -Dlifecycle.browser=true');
test('browser lifecycle uses real Java, persistent drafts and MQ media without CLI or model calls', async ({ page, request: worker }) => {
  test.setTimeout(180000);
  page.on('pageerror', error => console.error('Browser error:', error.message));
  const seed = JSON.parse(process.env.E2E_LIFECYCLE_SEED!);
  const base = process.env.E2E_BASE_URL!;
  const token = process.env.E2E_LIFECYCLE_TOKEN!;
  const post = async (path: string, body: unknown) => {
    const csrf = (await (await page.request.get(`${base}/api/v1/auth/csrf`)).json()).data.csrfToken;
    const response = await page.request.post(`${base}/api/v1${path}`, { headers: { 'X-XSRF-TOKEN': csrf, 'Idempotency-Key': randomUUID() }, data: body });
    expect(response.ok(), await response.text()).toBe(true); return (await response.json()).data;
  };
  const internal = async (path: string, body: unknown) => {
    const response = await worker.post(`${base}/internal/v1/agent-runs/${path}`, { headers: { Authorization: `Bearer ${token}` }, data: body });
    expect(response.ok(), await response.text()).toBe(true); return (await response.json()).data;
  };
  const canonical = (value: any): string => value === null || typeof value !== 'object' ? JSON.stringify(value) : Array.isArray(value) ? `[${value.map(canonical).join(',')}]` : `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}`;
  const hash = (value: unknown) => createHash('sha256').update(canonical(value)).digest('hex');
  await post('/auth/login', { username: 'm4-silent-owner', password: 'project-strong-password' });
  await page.goto(`/?project=${seed.projectId}`);
  await page.getByRole('tab', { name: '制作', exact: true }).click();
  const created = page.waitForResponse(response => response.url().endsWith('/conversations') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '新聊天', exact: true }).click();
  const newChat = await created; expect(newChat.status()).toBe(201);
  await expect(page.getByLabel('制作会话', { exact: true })).toHaveValue((await newChat.json()).data.id);
  await expect(page.getByLabel('对话输入', { exact: true })).toBeVisible();
  await expect(page.getByLabel('需求类型', { exact: true })).toHaveCount(0);
  const plans = async () => (await (await page.request.get(`${base}/api/v1/projects/${seed.projectId}/plans`)).json()).data.items;
  const baselinePlans = (await plans()).length;
  const send = async (content: string) => {
    await page.getByRole('tab', { name: '制作', exact: true }).click();
    await page.getByLabel('对话输入', { exact: true }).fill(content);
    const response = page.waitForResponse(response => response.url().endsWith('/turns') && response.request().method() === 'POST');
    await page.getByRole('button', { name: '发送需求', exact: true }).click();
    const accepted = await response; expect(accepted.status()).toBe(202);
    expect(accepted.request().postDataJSON()).not.toHaveProperty('context');
    return (await accepted.json()).data;
  };
  const bind = async (run: any, mode: string, relation: string, conditionsPatch: unknown = {}, questionId: string | null = null) => {
    const claim = await internal(`${run.taskId}/claim`, { executorId: 'browser-fixture', claimRequestId: randomUUID() });
    const credentials = { attemptId: claim.attemptId, leaseToken: claim.leaseToken };
    const binding = await internal(`${run.taskId}/parsed`, { ...credentials, parsed: { mode, relation, conditionsPatch, questionId } });
    return { run, credentials, binding, mode };
  };
  const publish = async (execution: any, status: string, content: string, extra: Record<string, unknown> = {}) => {
    const { run, credentials, binding, mode } = execution;
    await internal(`${run.taskId}/result`, { ...credentials, result: { schemaVersion: '1.0', identity: binding.identity, status, mode, content, scopeReceipts: [], productionId: binding.production?.productionId ?? null, editGeneration: binding.production?.editGeneration ?? null, draft: null, question: null, failure: null, ...extra } });
    await expect(page.getByRole('article', { name: '助手答复', exact: true }).filter({ hasText: content })).toBeVisible();
  };
  const tool = async (execution: any, name: string, args: unknown) => {
    const result = await internal(`${execution.run.taskId}/tools`, { ...execution.credentials, editGeneration: execution.binding.production?.editGeneration ?? null, request: { call_id: randomUUID(), tool_name: name, arguments: args, request_hash: hash({ tool: name, args }) } });
    return result;
  };
  const draft = async (execution: any, length: number, label: string) => {
    await tool(execution, 'read_video_range', { asset_id: seed.assetId, start_ms: 0, end_ms: 2000 });
    const content = { title: label, outputs: ['out-1', 'out-2'].map(output_key => ({ output_key, title: `${label}-${output_key}`, clips: [{ asset_id: seed.assetId, source_in_ms: 0, source_out_ms: output_key === 'out-1' ? 2000 : length, evidence_ids: [seed.evidenceId], reason: '已读红色矩形观察' }] })) };
    const requirements = execution.binding.production.requirements;
    const checked = await tool(execution, 'validate_edit_draft', { draft: content, requirements, draft_hash: hash(content), requirements_hash: hash(requirements) });
    expect(checked.data.valid, JSON.stringify(checked)).toBe(true);
    const binding = { messageId: randomUUID(), validationId: checked.data.validation_id, editGeneration: execution.binding.production.editGeneration, draftHash: hash(content), requirementsHash: hash(requirements) };
    await publish(execution, 'DRAFT_READY', label, { draft: binding });
    return binding;
  };
  await publish(await bind(await send('先讨论剪辑结构'), 'DISCUSS', 'INDEPENDENT'), 'ANSWER', '先呈现主体，再安排结尾。');
  expect(await plans()).toHaveLength(baselinePlans);
  const qa = await bind(await send('画面里有什么？'), 'QUERY', 'INDEPENDENT');
  await tool(qa, 'read_video_range', { asset_id: seed.assetId, start_ms: 0, end_ms: 2000 });
  const receipts = (await internal(`${qa.run.taskId}/receipts`, qa.credentials));
  await publish(qa, 'ANSWER', '观察到红色矩形。', { scopeReceipts: [{ scopeId: qa.binding.scope.scope_id, callId: receipts[0].callId, evidenceIds: [seed.evidenceId] }] });
  await page.getByRole('button', { name: '核查原视频证据', exact: true }).click();
  await expect.poll(() => page.getByLabel('视频播放器', { exact: true }).evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(1);
  const a = await draft(await bind(await send('制作两条静音竖屏短片'), 'DRAFT', 'NEW_PRODUCTION', { topic: '红色矩形', profile: 'PORTRAIT_720', subtitles_enabled: false, output_count: 2 }), 2000, '草稿 A');
  expect(await plans()).toHaveLength(baselinePlans);
  await page.getByRole('button', { name: '预览草稿', exact: true }).click();
  await page.getByLabel('选择预览输出', { exact: true }).selectOption('out-2');
  await page.getByRole('button', { name: '预览所选输出', exact: true }).click();
  await expect(page.getByRole('button', { name: '播放草稿预览', exact: true })).toBeVisible({ timeout: 60000 });
  await page.getByRole('button', { name: '播放草稿预览', exact: true }).click();
  const video = page.getByLabel('聊天草稿预览播放器', { exact: true });
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(1);
  expect(await video.evaluate((node: HTMLVideoElement) => [node.videoWidth, node.videoHeight])).toEqual([360, 640]);
  await video.evaluate(async (node: HTMLVideoElement) => { await node.play(); });
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.currentTime)).toBeGreaterThan(0.1);
  await video.evaluate((node: HTMLVideoElement) => node.pause());
  expect(await plans()).toHaveLength(baselinePlans);
  await page.screenshot({ path: '../backend/target/conversation-lifecycle-preview.png', fullPage: true });
  await page.reload();
  await expect(page.getByRole('button', { name: '确认全部输出', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '播放草稿预览', exact: true })).toBeVisible();
  await publish(await bind(await send('只讨论开场是否简洁'), 'DISCUSS', 'INDEPENDENT'), 'ANSWER', '可以保持简洁开场。');
  await expect(page.getByRole('button', { name: '确认全部输出', exact: true })).toBeEnabled();
  const editRun = await send('将第二条缩短，其他条件保留');
  await expect(page.getByRole('button', { name: '确认全部输出', exact: true })).toBeDisabled();
  const b = await draft(await bind(editRun, 'DRAFT', 'CONTINUE_PRODUCTION'), 1500, '草稿 B');
  expect(b.messageId).not.toBe(a.messageId);
  await expect(page.getByText(`历史草稿 · ${a.messageId} · 只读`, { exact: true })).toBeVisible();
  await expect(page.getByText(new RegExp(`来源草稿：${a.messageId}.*历史预览`))).toBeVisible();
  await page.getByRole('button', { name: '确认全部输出', exact: true }).click();
  await expect.poll(async () => (await plans()).length).toBe(baselinePlans + 1);
  await expect(page.getByRole('button', { name: '确认全部输出', exact: true })).toBeDisabled();
  await expect(page.getByLabel('查看方案', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: '查看已确认方案', exact: true }).click();
  await expect(page.getByText('当前版本已确认；导出仍需另行操作。', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '确认当前版本', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '导出正式成片', exact: true }).click();
  await page.getByLabel('选择导出输出', { exact: true }).selectOption({ label: '草稿 B-out-2' });
  await page.getByRole('button', { name: '导出所选输出', exact: true }).click();
  await expect(page.getByRole('button', { name: '播放正式成片', exact: true })).toBeVisible({ timeout: 60000 });
  await page.getByRole('button', { name: '播放正式成片', exact: true }).click();
  const finalVideo = page.getByLabel('正式成片播放器', { exact: true });
  await expect.poll(() => finalVideo.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(1);
  expect(await finalVideo.evaluate((node: HTMLVideoElement) => [node.videoWidth, node.videoHeight])).toEqual([720, 1280]);
  await finalVideo.evaluate(async (node: HTMLVideoElement) => { await node.play(); });
  await expect.poll(() => finalVideo.evaluate((node: HTMLVideoElement) => node.currentTime)).toBeGreaterThan(0.1);
  await finalVideo.evaluate((node: HTMLVideoElement) => node.pause());
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载正式成片', exact: true }).click();
  expect(await (await download).failure()).toBeNull();
  await page.getByLabel('成片导出清晰度', { exact: true }).selectOption('FULL_HD_1080');
  await page.getByRole('button', { name: '导出正式成片', exact: true }).click();
  await page.getByLabel('选择导出输出', { exact: true }).selectOption({ label: '草稿 B-out-2' });
  const fullHdAccepted = page.waitForResponse(response => response.url().endsWith('/export-requests') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '导出所选输出', exact: true }).click();
  expect((await fullHdAccepted).status()).toBe(202);
  await expect(finalVideo).toHaveCount(0);
  await page.getByRole('button', { name: '播放正式成片', exact: true }).click({ timeout: 60000 });
  await expect.poll(() => finalVideo.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(1);
  expect(await finalVideo.evaluate((node: HTMLVideoElement) => [node.videoWidth, node.videoHeight])).toEqual([1080, 1920]);
  await finalVideo.evaluate(async (node: HTMLVideoElement) => { await node.play(); });
  await expect.poll(() => finalVideo.evaluate((node: HTMLVideoElement) => node.currentTime)).toBeGreaterThan(0.1);
  await finalVideo.evaluate((node: HTMLVideoElement) => node.pause());
  await page.reload();
  await expect(page.getByText('当前版本已确认；导出仍需另行操作。', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '播放正式成片', exact: true })).toBeVisible();
  await publish(await bind(await send('接受后继续讨论下一条'), 'DISCUSS', 'INDEPENDENT'), 'ANSWER', '可以开始新的制作需求。');
  const failed = await bind(await send('继续讨论但执行中断'), 'DISCUSS', 'INDEPENDENT');
  await publish(failed, 'FAILED', '执行中断，可恢复', { failure: { code: 'EXECUTION_INTERRUPTED', message: '执行中断，可恢复', recoverable: true } });
  const retried = page.waitForResponse(response => response.url().endsWith(`/tasks/${failed.run.taskId}/retry`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: '重试原需求', exact: true }).click();
  const retryResponse = await retried; expect(retryResponse.status()).toBe(202);
  const retry = (await retryResponse.json()).data;
  const retryClaim = await internal(`${retry.taskId}/claim`, { executorId: 'browser-fixture', claimRequestId: randomUUID() });
  await publish({ ...failed, run: retry, credentials: { attemptId: retryClaim.attemptId, leaseToken: retryClaim.leaseToken }, binding: retryClaim.binding }, 'ANSWER', '恢复原执行完成。');
  const uncertain = await bind(await send('讨论不确定调用'), 'DISCUSS', 'INDEPENDENT');
  await publish(uncertain, 'INCOMPLETE', '模型提交状态未知，停止自动重付。', { failure: { code: 'PAID_SUBMISSION_UNKNOWN', message: '模型提交状态未知，停止自动重付。', recoverable: false } });
  await expect(page.getByRole('button', { name: '重试原需求', exact: true })).toHaveCount(0);
  const waiting = await bind(await send('另起一项制作，先确定时长'), 'DRAFT', 'NEW_PRODUCTION', { topic: '新的独立主题' });
  const questionId = randomUUID();
  await publish(waiting, 'WAITING_INPUT', '新制作需要多少秒？', { question: { questionId, taskId: waiting.run.taskId, productionId: waiting.binding.production.productionId, threadId: waiting.binding.identity.threadId, executionId: waiting.binding.identity.executionId, waitId: 'duration-wait', editGeneration: waiting.binding.production.editGeneration, prompt: '新制作需要多少秒？' } });
  await expect(page.getByRole('region', { name: '待回答问题', exact: true })).toContainText('新制作需要多少秒');
  await publish(await bind(await send('先独立讨论节奏'), 'DISCUSS', 'INDEPENDENT'), 'ANSWER', '讨论节奏不会消费原问题。');
  await expect(page.getByRole('region', { name: '待回答问题', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '引用此问题', exact: true }).click();
  const answer = await bind(await send('60 秒'), 'DRAFT', 'ANSWER_QUESTION', { duration_min_ms: 60000, duration_max_ms: 60000 }, questionId);
  await publish(answer, 'INCOMPLETE', '预算已耗尽，保留新的制作条件。', { failure: { code: 'BUDGET_EXHAUSTED', message: '预算已耗尽，保留新的制作条件。', recoverable: false } });
  await expect(page.getByRole('region', { name: '待回答问题', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '重试原需求', exact: true })).toHaveCount(0);
  expect(await plans()).toHaveLength(baselinePlans + 1);
  await page.screenshot({ path: '../backend/target/conversation-lifecycle-desktop.png', fullPage: true });
  // An externally lost export must still restore its record without a server error.
  await page.getByRole('tab', { name: '作品', exact: true }).click();
  await page.getByLabel('查看方案', { exact: true }).selectOption(seed.missingPlanId);
  await page.getByLabel('查看版本', { exact: true }).selectOption({ label: 'V1' });
  await expect(page.getByLabel('查看正式导出记录', { exact: true })).toBeVisible();
  const artifactRead = page.waitForResponse(response => response.url().endsWith(`/artifacts/${seed.missingArtifactId}`) && response.request().method() === 'GET');
  await page.getByLabel('查看正式导出记录', { exact: true }).selectOption(seed.missingExportId);
  const missingResponse = await artifactRead;
  expect(missingResponse.status()).toBe(200);
  expect((await missingResponse.json()).data.storedBytes).toBe(0);
  await expect(page.getByRole('region', { name: '编排剪辑方案', exact: true }).getByRole('alert')).toHaveCount(0);
  await page.getByRole('button', { name: '播放正式成片', exact: true }).click();
  await expect(page.getByRole('region', { name: '编排剪辑方案', exact: true }).getByRole('alert')).toContainText('产物不可用');
  const deletion = page.waitForResponse(response => response.url().endsWith(`/artifacts/${seed.missingArtifactId}`) && response.request().method() === 'DELETE');
  await page.getByRole('button', { name: '删除成片文件', exact: true }).click();
  const deleted = await deletion; expect(deleted.status()).toBe(200);
  expect((await deleted.json()).data.removedBytes).toBe(0);
  await expect(page.getByText('成片文件已删除，原始素材保留。', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByLabel('查看正式导出记录', { exact: true }).selectOption(seed.missingExportId);
  await expect(page.getByText('成片文件已删除，原始素材保留。', { exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: '编排剪辑方案', exact: true }).getByRole('alert')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: '制作', exact: true }).click();
  await expect(page.getByLabel('对话输入', { exact: true })).toBeVisible();
  await page.screenshot({ path: '../backend/target/conversation-lifecycle-mobile.png', fullPage: true });
});
